"""Build pipeline/run_place.py from the two Colab notebooks, so the robot runs exactly the code people run by hand.

Run this whenever a notebook changes:  python3 pipeline/make_run_place.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def code_cells(name):
    nb = json.load(open(os.path.join(ROOT, "notebooks", name)))
    out = []
    for c in nb["cells"]:
        if c["cell_type"] != "code":
            continue
        src = "".join(c["source"])
        first = src.strip().splitlines()[0] if src.strip() else ""
        if src.lstrip().startswith("!") or "Install the free tools" in first:
            continue
        out.append((first, src))
    return out


place = code_cells("threadlands-place-builder.ipynb")
heat = code_cells("threadlands-heat-check.ipynb")
# Leave out the settings cell (set from the command line) and the quick-look plot
place = [(t, s) for t, s in place if "Settings" not in t and "quick look" not in t.lower()]
heat = [(t, s.replace("PLACE_FILE = None ", "PLACE_FILE = PLACE_FILE ")) for t, s in heat]
assert len(place) == 10, [t for t, _ in place]
assert len(heat) == 5, [t for t, _ in heat]
assert "PLACE_FILE = PLACE_FILE" in heat[1][1]

parts = ['''# Generated by pipeline/make_run_place.py from the Colab notebooks. Do not edit by hand.
# Usage: python3 run_place.py "Lagos, Nigeria" /path/to/lagos.json
import sys, os, json, shutil, traceback
PLACE = sys.argv[1]
FINAL_OUT = os.path.abspath(sys.argv[2])
REGION_BUFFER_KM = None
MAX_HEXES = int(os.environ.get('TL_MAX_HEXES', '2500'))
''']
for title, src in place:
    parts.append("\n# ---- " + title.lstrip("# ") + "\n" + src + "\n")
parts.append('''
# ---- Keep the place file even if the heat check fails
shutil.copyfile(OUT, FINAL_OUT)
print("PLACE_OK", FINAL_OUT)
PLACE_FILE = OUT
HEAT_CODE = %r
try:
    exec(HEAT_CODE, globals())
    shutil.copyfile(OUT, FINAL_OUT)
    print("HEAT_OK")
except BaseException as e:
    print("HEAT_FAILED:", repr(e))
    traceback.print_exc()
''' % "\n".join(src for _, src in heat))
out = os.path.join(ROOT, "pipeline", "run_place.py")
open(out, "w").write("".join(parts))
compile(open(out).read(), out, "exec")
print("wrote", out)
